// 模块 16 写博客编排·审校基础设施：评审判定解析 + 研究段/写作段两套评审提示词。
// parseCriticVerdict 移植自 10-multi-agent/critic.ts（首行 PASS/FAIL 英文短锚 + 中文同义锚
// 「通过/不通过」+ 违约 fail-closed 诊断）。两个评审提示词是工作台博客场景的新写判据：
// 审校① 判「简报是否锚定真实素材」（防写手脱离用户实际学过的东西自由发挥），
// 审校② 判「稿件对简报的忠实转写」（简报已过审，写手不得脱离它）。
export interface CriticVerdict {
  passed: boolean
  issues: string[]
}

export function parseCriticVerdict(criticConclusion: string): CriticVerdict {
  const lines = criticConclusion.split('\n').filter((l) => l.trim())
  const first = (lines[0] ?? '').trim().toUpperCase()
  // 首行锚定：PASS 精确匹配（防「PASS 但还有下文」的半通过）；FAIL 同理
  if (first === 'PASS' && lines.length === 1) return { passed: true, issues: [] }
  if (first === 'FAIL') return { passed: false, issues: lines.slice(1) }
  // 同义锚收编：critic 实质批准但写中文「通过」——精确匹配收编安全（「不通过」≠「通过」整串比较），
  // 歧义不收（「检查不通过」「大致通过」照走违约分支）
  if (first === '通过' && lines.length === 1) return { passed: true, issues: [] }
  if (first === '不通过') return { passed: false, issues: lines.slice(1) }
  // 解析失败（空输入 / 首行既非 PASS 也非 FAIL / PASS 后拖了别的话）：fail-closed——
  // 不放行（坏稿代价 > 一轮重跑），把违约本身合成诊断 issue 喂下去
  return {
    passed: false,
    issues: [
      `[评审契约违约] critic 输出未按「首行 PASS/FAIL」契约，原文头 80 字：${criticConclusion.slice(0, 80)}——请评审方严格遵守输出契约后重评`,
    ],
  }
}

// ---------- 评审提示词（工作台博客场景判据） ----------
// 共同纪律段（照抄 10-multi-agent/critic.ts 的「判据全集+不挤牙膏」条款）：
//   - 判据全集就是列出的几条，评审只许依据它们——修订逐轮变好时不得引入清单外新判据打回，
//     也不得为「总得挑毛病」打回；本轮无不合格项就是 PASS
//   - 输出契约：全部通过 → 首行只写 PASS 不要其他；有不通过项 → 首行只写 FAIL，随后每行一条
//     「编号 | 不通过项 | 原因 | 修订指令」；修订指令只给方向不代改

/** 审校①：研究段——判「研究简报」是否锚定真实素材、够不够下游写手成文 */
export function researchCriticPrompt(): string {
  return [
    '角色：你是研究段的评审员。交接物里有研究简报。你只评审、不代改；你没有任何工具，也不要尝试读文件、执行命令或调用任何东西——判断所需的一切已在交接物里。',
    '评审标准（逐条判定，只列不通过的）：',
    '1. 锚定性：简报每条要点必须能对应检索到的真实素材（来源标注真实、内容有依据），编造或来源对不上即不通过。',
    '2. 覆盖性：简报覆盖主题所需的主要方面，明显缺项不通过。',
    '3. 可用性：简报足够下游写手直接成文（有足够具体事实/数据/代码点可组织成文章），太空泛即不通过。',
    '判据全集就是上面三条，评审只许依据这三条，不做清单外的判定：随着修订逐轮变好，你不得引入清单外的新判据来打回，也不得为了「总得挑毛病」而打回——本轮三条都没有不通过的项，就是 PASS。',
    '输出契约（字面钉死，解析端按此判定）：全部通过 → 首行只写 PASS，不要输出其他任何内容；有不通过项 → 首行只写 FAIL，随后每行一条：编号 | 不通过项 | 原因 | 修订指令。',
    '修订指令只给方向不代改——你的产出是研究员下一轮的修订方向，不是改好的简报。',
  ].join('\n')
}

/** 审校②：写作段——判「稿件」对研究简报的忠实转写（简报已过审，稿件不得脱离它） */
export function writingCriticPrompt(): string {
  return [
    '角色：你是写作段的评审员。交接物里有研究简报和待审稿件。你只评审、不代改；你没有任何工具，也不要尝试读文件、执行命令或调用任何东西——判断所需的一切已在交接物里。',
    '评审标准（逐条判定，只列不通过的）：',
    '1. 忠实性：稿件中的事实、数据、技术点必须能在研究简报里找到依据，编造或脱离简报即不通过。',
    '2. 完整性：稿件结构完整（标题 + 引言 + 章节 + 总结），缺结构即不通过。',
    '3. 针对性：稿件贴近用户实际学过/做过的东西，写成泛泛的科普即不通过。',
    '判据全集就是上面三条，评审只许依据这三条，不做清单外的判定：随着修订逐轮变好，你不得引入清单外的新判据来打回，也不得为了「总得挑毛病」而打回——本轮三条都没有不通过的项，就是 PASS。',
    '输出契约（字面钉死，解析端按此判定）：全部通过 → 首行只写 PASS，不要输出其他任何内容；有不通过项 → 首行只写 FAIL，随后每行一条：编号 | 不通过项 | 原因 | 修订指令。',
    '修订指令只给方向不代改——你的产出是写手下一轮的修订方向，不是改好的稿子。',
  ].join('\n')
}
